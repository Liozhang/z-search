/**
 * Regenerate the locale key catalog and the FluentMessageId typings.
 *
 * Source of truth is the en-US Fluent union (addon + preferences + tracking),
 * read in file order. Two artifacts fall out of it:
 *   - src/locale-keys.generated.ts  — runtime key list (FTL order), consumed by
 *     src/bridge/localeBatch.ts to batch-resolve every key through Fluent.
 *   - typings/i10n.d.ts             — compile-time FluentMessageId union
 *     (alphabetical) so getString() rejects a typo'd key at build time.
 *
 * Usage:
 *   node scripts/gen-locale-keys.cjs           # write both artifacts
 *   node scripts/gen-locale-keys.cjs --check   # verify they are fresh (exit 1 if not)
 *
 * @module scripts/gen-locale-keys.cjs
 */

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const FAMILIES = ["addon", "preferences", "tracking"];

const CATALOG_PATH = path.join(ROOT, "src", "locale-keys.generated.ts");
const TYPINGS_PATH = path.join(ROOT, "typings", "i10n.d.ts");

const CATALOG_HEADER = [
  "// AUTO-GENERATED by scripts/gen-locale-keys.cjs — DO NOT EDIT MANUALLY",
  "// Source: addon/locale/en-US/*.ftl (en-US message union)",
  "// Re-run via `node scripts/gen-locale-keys.cjs` after touching the FTL files.",
  "/* prettier-ignore */",
].join("\n");

const TYPINGS_HEADER = [
  "// Generated by scripts/gen-locale-keys.cjs",
  "/* prettier-ignore */",
  "/* eslint-disable */",
  "// @ts-nocheck",
].join("\n");

/** Message IDs of one FTL family, in file order. Comments and attributes are skipped. */
function ftlKeys(file) {
  const ids = [];
  for (const rawLine of fs.readFileSync(file, "utf8").split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const m = line.match(/^([a-zA-Z0-9_-]+)\s*=/);
    if (m) ids.push(m[1]);
  }
  return ids;
}

function renderCatalog(keys) {
  return `${CATALOG_HEADER}\nexport const ALL_LOCALE_KEYS: readonly string[] = [\n${keys
    .map((k) => `  "${k}",`)
    .join("\n")}\n];\n`;
}

function renderTypings(keys) {
  const sorted = [...keys].sort();
  return `${TYPINGS_HEADER}\nexport type FluentMessageId =\n${sorted
    .map((k) => `  | '${k}'`)
    .join("\n")};\n`;
}

function main() {
  const keys = [];
  for (const family of FAMILIES) {
    keys.push(
      ...ftlKeys(path.join(ROOT, "addon", "locale", "en-US", `${family}.ftl`)),
    );
  }

  const seen = new Set();
  for (const k of keys) {
    if (seen.has(k)) {
      throw new Error(`duplicate message id across en-US FTL files: ${k}`);
    }
    seen.add(k);
  }

  const catalog = renderCatalog(keys);
  const typings = renderTypings(keys);
  const check = process.argv.includes("--check");

  if (check) {
    let fresh = true;
    for (const [file, next] of [
      [CATALOG_PATH, catalog],
      [TYPINGS_PATH, typings],
    ]) {
      if (fs.readFileSync(file, "utf8") !== next) {
        console.error(`stale: ${path.relative(ROOT, file)}`);
        fresh = false;
      }
    }
    process.exit(fresh ? 0 : 1);
  }

  fs.writeFileSync(CATALOG_PATH, catalog);
  fs.writeFileSync(TYPINGS_PATH, typings);
  console.log(
    `wrote ${keys.length} keys -> ${path.relative(ROOT, CATALOG_PATH)}, ${path.relative(ROOT, TYPINGS_PATH)}`,
  );
}

main();
